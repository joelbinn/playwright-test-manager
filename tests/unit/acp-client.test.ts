import { describe, it, expect, beforeEach, afterEach } from 'vitest';
import * as path from 'node:path';
import * as fs from 'node:fs/promises';
import * as os from 'node:os';
import { AcpClient, isPathWithinWorkspace } from '../../src/server/acp-client.js';

describe('ACP Client Subprocess Adapter (Seam: ACP Client Module)', () => {
  let tempDir: string;

  beforeEach(async () => {
    tempDir = await fs.mkdtemp(path.join(os.tmpdir(), 'ptm-acp-test-'));
  });

  afterEach(async () => {
    await fs.rm(tempDir, { recursive: true, force: true });
  });

  it('verifies path containment logic for workspace sandboxing', () => {
    expect(isPathWithinWorkspace(tempDir, path.join(tempDir, 'specs/test.md'))).toBe(true);
    expect(isPathWithinWorkspace(tempDir, path.join(tempDir, 'sub/nested/file.ts'))).toBe(true);
    expect(isPathWithinWorkspace(tempDir, path.join(tempDir, '../outside.txt'))).toBe(false);
    expect(isPathWithinWorkspace(tempDir, '/etc/passwd')).toBe(false);
  });

  it('negotiates handshake, ephemeral session, streams task chunks, and shuts down cleanly', async () => {
    // Helper ACP agent script running as a node child process
    const mockAgentScript = path.join(tempDir, 'fake-acp-agent.js');
    await fs.writeFile(
      mockAgentScript,
      `
const readline = require('readline');
const rl = readline.createInterface({ input: process.stdin, output: process.stdout, terminal: false });

rl.on('line', (line) => {
  if (!line.trim()) return;
  const msg = JSON.parse(line);
  if (msg.method === 'initialize') {
    process.stdout.write(JSON.stringify({
      jsonrpc: '2.0',
      id: msg.id,
      result: { protocolVersion: '2024-11-05', capabilities: { sessions: true } }
    }) + '\\n');
  } else if (msg.method === 'notifications/initialized') {
    // Handshake complete
  } else if (msg.method === 'session/create') {
    process.stdout.write(JSON.stringify({
      jsonrpc: '2.0',
      id: msg.id,
      result: { sessionId: 'ephemeral-session-123' }
    }) + '\\n');
  } else if (msg.method === 'session/prompt') {
    // Stream chunks
    process.stdout.write(JSON.stringify({
      jsonrpc: '2.0',
      method: 'session/update',
      params: { sessionId: msg.params.sessionId, chunk: '# Generated by ACP\\n' }
    }) + '\\n');
    process.stdout.write(JSON.stringify({
      jsonrpc: '2.0',
      method: 'session/update',
      params: { sessionId: msg.params.sessionId, chunk: 'test("user login", () => {});' }
    }) + '\\n');

    // Complete prompt
    process.stdout.write(JSON.stringify({
      jsonrpc: '2.0',
      id: msg.id,
      result: { status: 'completed' }
    }) + '\\n');
  } else if (msg.method === 'session/close') {
    process.stdout.write(JSON.stringify({
      jsonrpc: '2.0',
      id: msg.id,
      result: { closed: true }
    }) + '\\n');
    process.exit(0);
  }
});
`,
      'utf-8'
    );

    const client = new AcpClient({
      command: 'node',
      args: [mockAgentScript],
      workspaceRoot: tempDir
    });

    const chunks: string[] = [];
    for await (const chunk of client.streamTask({
      role: 'planner',
      prompt: 'Generate login test'
    })) {
      chunks.push(chunk);
    }

    expect(chunks.join('')).toBe('# Generated by ACP\ntest("user login", () => {});');
    expect(client.isAlive()).toBe(false);
  });

  it('auto-approves permissions within workspace and blocks external operations', async () => {
    const mockAgentScript = path.join(tempDir, 'fake-permission-agent.js');
    await fs.writeFile(
      mockAgentScript,
      `
const readline = require('readline');
const rl = readline.createInterface({ input: process.stdin, output: process.stdout, terminal: false });

let promptId = null;

rl.on('line', (line) => {
  if (!line.trim()) return;
  const msg = JSON.parse(line);
  if (msg.method === 'initialize') {
    process.stdout.write(JSON.stringify({ jsonrpc: '2.0', id: msg.id, result: {} }) + '\\n');
  } else if (msg.method === 'notifications/initialized') {
    // Ask for permission for inside workspace
    process.stdout.write(JSON.stringify({
      jsonrpc: '2.0',
      id: 100,
      method: 'permission/request',
      params: { path: '${path.join(tempDir, 'specs/foo.md').replace(/\\/g, '\\\\')}' }
    }) + '\\n');
  } else if (msg.id === 100) {
    // Received response for inside workspace; now ask for outside workspace
    process.stdout.write(JSON.stringify({
      jsonrpc: '2.0',
      method: 'session/update',
      params: { chunk: 'inside:' + msg.result.approved }
    }) + '\\n');

    process.stdout.write(JSON.stringify({
      jsonrpc: '2.0',
      id: 200,
      method: 'permission/request',
      params: { path: '/etc/passwd' }
    }) + '\\n');
  } else if (msg.id === 200) {
    process.stdout.write(JSON.stringify({
      jsonrpc: '2.0',
      method: 'session/update',
      params: { chunk: ',outside:' + msg.result.approved }
    }) + '\\n');

    if (promptId !== null) {
      process.stdout.write(JSON.stringify({
        jsonrpc: '2.0',
        id: promptId,
        result: { status: 'completed' }
      }) + '\\n');
    }
  } else if (msg.method === 'session/create') {
    process.stdout.write(JSON.stringify({ jsonrpc: '2.0', id: msg.id, result: { sessionId: 's-1' } }) + '\\n');
  } else if (msg.method === 'session/prompt') {
    promptId = msg.id;
  } else if (msg.method === 'session/close') {
    process.stdout.write(JSON.stringify({ jsonrpc: '2.0', id: msg.id, result: { closed: true } }) + '\\n');
    process.exit(0);
  }
});
`,
      'utf-8'
    );

    const client = new AcpClient({
      command: 'node',
      args: [mockAgentScript],
      workspaceRoot: tempDir
    });

    const chunks: string[] = [];
    for await (const chunk of client.streamTask({
      role: 'generator',
      prompt: 'Test permissions'
    })) {
      chunks.push(chunk);
    }

    expect(chunks.join('')).toBe('inside:true,outside:false');
  });

  it('aborts cleanly and terminates subprocess when AbortController triggers', async () => {
    const mockAgentScript = path.join(tempDir, 'fake-hanging-agent.js');
    await fs.writeFile(
      mockAgentScript,
      `
const readline = require('readline');
const rl = readline.createInterface({ input: process.stdin, output: process.stdout, terminal: false });

rl.on('line', (line) => {
  if (!line.trim()) return;
  const msg = JSON.parse(line);
  if (msg.method === 'initialize') {
    process.stdout.write(JSON.stringify({ jsonrpc: '2.0', id: msg.id, result: {} }) + '\\n');
  } else if (msg.method === 'session/create') {
    process.stdout.write(JSON.stringify({ jsonrpc: '2.0', id: msg.id, result: { sessionId: 's-hang' } }) + '\\n');
  } else if (msg.method === 'session/prompt') {
    // send one chunk then hang
    process.stdout.write(JSON.stringify({
      jsonrpc: '2.0',
      method: 'session/update',
      params: { chunk: 'started' }
    }) + '\\n');
  }
});
`,
      'utf-8'
    );

    const client = new AcpClient({
      command: 'node',
      args: [mockAgentScript],
      workspaceRoot: tempDir
    });

    const abortController = new AbortController();
    const chunks: string[] = [];

    try {
      for await (const chunk of client.streamTask({
        role: 'healer',
        prompt: 'Repair test',
        signal: abortController.signal
      })) {
        chunks.push(chunk);
        if (chunk === 'started') {
          abortController.abort();
        }
      }
    } catch (err: any) {
      // Abort error expected
    }

    expect(chunks).toContain('started');
    // Allow process cleanup tick
    await new Promise((r) => setTimeout(r, 100));
    expect(client.isAlive()).toBe(false);
  });
});
